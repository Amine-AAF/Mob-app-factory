import type { Repositories } from '@/database';
import type { Category, Transaction } from '@/types';
import { addMonths, monthEnd, monthOf, monthStart, monthsBetweenInclusive, periodRange, previousPeriod, type DateRange, type DayKey, type MonthKey, type PeriodKind } from '@/utils/dates';

import { evaluateBudget, type BudgetLine } from '../budgets/budgets';
import { buildInsights, type Insight } from './insights';
import { dailySpending, monthlyTrend, rankCategories, rateMap, savingsRate, summarize, type Summary } from './stats';

export interface ReportFilters {
  accountId?: string;
  categoryId?: string;
}

export interface ReportData {
  kind: PeriodKind;
  range: DateRange;
  previousRange: DateRange;
  currency: string;
  summary: Summary;
  previous: Summary;
  spendingCategories: { categoryId: string; amount: number }[];
  incomeCategories: { categoryId: string; amount: number }[];
  /** Daily spending for week/month views. */
  daily: { day: DayKey; amount: number }[] | null;
  /** Monthly income vs spending: 12 months of the year (year view) or last 6 months otherwise. */
  trend: { month: MonthKey; income: number; spending: number }[];
  /** Budget vs actual (month view only, when a budget exists in the report currency). */
  budget: { total: BudgetLine; categories: BudgetLine[]; currency: string } | null;
  /** Recurring spending in the period (expenses generated by recurring rules). */
  recurringSpending: number;
  savingsRate: number | null;
  insights: Insight[];
  categories: Map<string, Category>;
}

function applyFilters(txs: readonly Transaction[], f: ReportFilters): Transaction[] {
  // Account filter: only transactions whose SOURCE account matches count as that account's
  // income/spending. Transfers are excluded from statistics anyway (summarize).
  return txs.filter((t) => (!f.accountId || t.accountId === f.accountId) && (!f.categoryId || t.categoryId === f.categoryId));
}

/**
 * Loads every figure of the Reports screen from the transactions really recorded.
 * Nothing is estimated or invented: empty periods produce zeros and no insight.
 */
export async function loadReport(r: Repositories, kind: PeriodKind, anchor: DayKey, filters: ReportFilters, mainCurrency: string): Promise<ReportData> {
  const range = periodRange(kind, anchor);
  const prevRange = previousPeriod(kind, anchor);
  const trendMonths = kind === 'year' ? monthsBetweenInclusive(monthOf(range.start), monthOf(range.end)) : monthsBetweenInclusive(addMonths(monthOf(range.end), -5), monthOf(range.end));
  const trendFrom = monthStart(trendMonths[0]!);
  const trendTo = monthEnd(trendMonths[trendMonths.length - 1]!);
  const from = [range.start, prevRange.start, trendFrom].sort()[0]!;
  const to = [range.end, trendTo].sort().reverse()[0]!;

  const [all, rates, categories, settings] = await Promise.all([
    r.transactions.list({ from, to, order: 'asc' }),
    r.rates.list(),
    r.categories.list({ includeArchived: true }),
    r.settings.getAll(),
  ]);
  const rm = rateMap(rates);
  const txs = applyFilters(all, filters);
  const inRange = (t: Transaction, d: DateRange) => t.date >= d.start && t.date <= d.end;
  const current = txs.filter((t) => inRange(t, range));
  const prevTxs = txs.filter((t) => inRange(t, prevRange));

  const summary = summarize(current, mainCurrency, rm);
  const previous = summarize(prevTxs, mainCurrency, rm);

  let budget: ReportData['budget'] = null;
  if (kind === 'month' && !filters.accountId) {
    const b = await r.budgets.getByMonth(monthOf(range.start));
    if (b) {
      const s = b.budget.currency === mainCurrency && !filters.categoryId ? summary : summarize(all.filter((t) => inRange(t, range)), b.budget.currency, rm);
      const e = evaluateBudget(b.budget, b.limits, s.spendingByCategory, s.spending, settings.alertThresholds);
      budget = {
        ...e,
        categories: filters.categoryId ? e.categories.filter((c) => c.scope === filters.categoryId) : e.categories,
        currency: b.budget.currency,
      };
    }
  }

  const recurringSpending = summarize(
    current.filter((t) => t.recurringRuleId && (t.type === 'expense' || t.type === 'refund')),
    mainCurrency,
    rm,
  ).spending;

  return {
    kind,
    range,
    previousRange: prevRange,
    currency: mainCurrency,
    summary,
    previous,
    spendingCategories: rankCategories(summary.spendingByCategory),
    incomeCategories: rankCategories(summary.incomeByCategory),
    daily: kind === 'year' ? null : dailySpending(current, range, mainCurrency, rm),
    trend: monthlyTrend(txs.filter((t) => t.date >= trendFrom && t.date <= trendTo), trendMonths, mainCurrency, rm),
    budget,
    recurringSpending,
    savingsRate: savingsRate(summary),
    insights: buildInsights(summary, previous),
    categories: new Map(categories.map((c) => [c.id, c])),
  };
}
