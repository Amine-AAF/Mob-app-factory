#!/usr/bin/env node
/**
 * Merges the per-feature JSON files in locales/<lng>/<namespace>.json into one file per
 * language, locales/<lng>.json (the factory convention checked by `pnpm registry:check`),
 * and writes resources.ts. Each namespace file becomes a top-level key:
 * locales/en/wardrobe.json -> t('wardrobe.…').
 *
 * Edit the per-namespace files, never the generated locales/<lng>.json. Then run:
 *   node src/i18n/generate-resources.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const dir = path.join(import.meta.dirname, 'locales');
const langs = ['en', 'fr', 'es'];
const names = fs
  .readdirSync(path.join(dir, 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''))
  .sort();

for (const lng of langs) {
  const merged = {};
  for (const n of names) {
    const file = path.join(dir, lng, `${n}.json`);
    if (!fs.existsSync(file)) throw new Error(`Missing ${lng}/${n}.json`);
    merged[n] = JSON.parse(fs.readFileSync(file, 'utf8'));
  }
  fs.writeFileSync(path.join(dir, `${lng}.json`), `${JSON.stringify(merged, null, 2)}\n`);
}

let out = '/* Generated by generate-resources.mjs — do not edit by hand. */\n';
for (const l of langs) out += `import ${l} from './locales/${l}.json';\n`;
out += `\nexport { ${langs.join(', ')} };\n`;
fs.writeFileSync(path.join(import.meta.dirname, 'resources.ts'), out);
// eslint-disable-next-line no-console -- CLI script: reports what it generated
console.log(`locales/{${langs.join(',')}}.json + resources.ts: ${names.length} namespaces`);
